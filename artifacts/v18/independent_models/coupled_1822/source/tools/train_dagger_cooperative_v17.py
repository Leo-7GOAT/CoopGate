"""Coupled API with on-policy dataset aggregation inside each actor update.

The rollout expert is generated from the frozen current JOINT policy, not from
an external planning teacher. Other actors react in every branch. Each updated
actor is trained on trajectories increasingly generated by its own new policy.
"""
import argparse,copy,csv,hashlib,json,shutil,subprocess,time
from pathlib import Path
import numpy as np
import torch
from coopgate.cooperative_iteration_v16 import load_coupled,unilateral_returns
from coopgate.cooperative_v15 import CooperativeVector
from train_cooperative_iteration_v16 import fit_actor
from prerequisite_v15 import require_single

ROOT=Path(__file__).resolve().parents[1]


def train(out,warmstart,seed=1701,cycles=2,states=4096,epochs=80):
    prerequisite=require_single(ROOT)
    if cycles<1 or states<32 or epochs<1:raise ValueError('Positive complete training budget required')
    torch.set_num_threads(1);torch.manual_seed(seed);rng=np.random.default_rng(seed)
    warmstart=Path(warmstart);model,parent=load_coupled(warmstart)
    if parent['updates']!=parent['target_updates']:raise ValueError('Use a complete frozen parent policy')
    out=Path(out);out.mkdir(parents=True,exist_ok=False)
    for p in model.critics.parameters():p.requires_grad_(False)
    initial={k:v.detach().clone() for k,v in model.state_dict().items()};order=[0,2,1];mix=[1.,.5,0.]
    meta=dict(algorithm='coupled_policy_iteration_v16',checkpoint_format='compatible V16 joint actors',
        training_variant='dagger_coupled_api_v17',seed=seed,ego_seed=parent['ego_seed'],actor_width=model.width,
        cycles=cycles,target_updates=cycles*3,actor_update_order=order,trainable_vehicles=[0,1,2],
        states_per_pass=states,states_per_update=states*len(mix),epochs=epochs,
        rollout_expert_mixing_probabilities=mix,
        warmstart=str(warmstart).replace('\\','/'),warmstart_sha256=hashlib.sha256(warmstart.read_bytes()).hexdigest(),
        initialization='Continuation of the complete parent joint policy; not a new independent random initialization',
        objective='Mean individual arrival plus 0.05 individual variation, each stopped at own arrival',
        teacher='Argmin of complete nominal branch returns under the frozen current joint policy; no external planner labels',
        training_backend='Exact model, four hidden disturbance modes for visitation; nominal counterfactual branches',
        policy_improvement='One actor at a time, frozen full joint policy within each update, three dataset-aggregation passes',
        inference='Local neural proposals and shared physical filter; no online performance rollout',
        checkpoint_selection='Fixed final sixth update at default two cycles, no evaluation-based checkpoint selection',
        prerequisite=prerequisite,source_commit=subprocess.check_output(['git','rev-parse','HEAD'],cwd=ROOT,text=True).strip())
    files=list((ROOT/'src/coopgate').glob('*.py'))+[Path(__file__),ROOT/'tools/train_cooperative_iteration_v16.py',ROOT/'tools/prerequisite_v15.py']
    meta['source_sha256']={str(p.resolve().relative_to(ROOT)).replace('\\','/'):hashlib.sha256(p.read_bytes()).hexdigest() for p in files}
    for name in meta['source_sha256']:
        target=out/'source'/name;target.parent.mkdir(parents=True,exist_ok=True);shutil.copy2(ROOT/name,target)
    (out/'protocol.json').write_text(json.dumps(meta,indent=2)+'\n')
    torch.save({**meta,'updates':0,'model':model.state_dict()},out/'initial.pt')
    history=[];pass_history=[];visited=branches=environment_steps=0;started=time.perf_counter()
    for update in range(cycles*3):
        role=order[update%3];reference=copy.deepcopy(model).eval();stored=[]
        for pass_index,beta in enumerate(mix):
            env=CooperativeVector(32,82000000+seed*100+update*3+pass_index);count=0
            while count<states:
                obs,_,mask=env.inputs();ids=np.flatnonzero(env.x[:,role,0]<60)[:states-count]
                actions=model.proposal(obs,mask)
                if len(ids):
                    costs,incumbent,evaluated=unilateral_returns(env.x[ids],env.previous[ids],env.steps[ids],reference,role)
                    stored.append((obs[ids,role].copy(),costs,incumbent,env.x[ids].copy(),env.previous[ids].copy(),env.steps[ids].copy()))
                    best=costs.min(1);optimal=costs<=best[:,None]+1e-9
                    expert=np.where(optimal,np.arange(costs.shape[1]),-1).max(1)
                    retain=costs[np.arange(len(ids)),incumbent]<=best+1e-9;expert[retain]=incumbent[retain]
                    actions[ids,role]=np.where(rng.random(len(ids))<beta,expert,actions[ids,role])
                    count+=len(ids);branches+=evaluated;visited+=len(ids)
                env.step(actions);environment_steps+=env.n
            data=[np.concatenate([r[i] for r in stored]) for i in range(6)]
            stats=fit_actor(model.actors[role],data[0],data[1],data[2],rng,epochs)
            pass_history.append(dict(update=update+1,role=role,aggregation_pass=pass_index+1,
                rollout_expert_probability=beta,states_in_fit=len(data[0]),**stats))
            print(json.dumps(dict(update=update+1,role=role,aggregation_pass=pass_index+1,
                training_action_regret=stats['training_action_regret'],elapsed_s=time.perf_counter()-started)),flush=True)
        ob,costs,incumbent,x,previous,clock=data
        np.savez_compressed(out/f'data_{update+1}.npz',obs=ob,costs=costs,incumbent=incumbent,states=x,previous=previous,steps=clock)
        for key,value in reference.state_dict().items():
            if not key.startswith(f'actors.{role}.'):assert torch.equal(value,model.state_dict()[key])
        changes=[sum(float((value-initial[key]).square().sum()) for key,value in model.state_dict().items()
            if key.startswith(f'actors.{i}.')) for i in range(3)]
        row=dict(updates=update+1,role=role,visited_states=visited,joint_environment_steps=environment_steps,
            evaluated_model_transitions=branches,**stats,elapsed_s=time.perf_counter()-started,
            actor0_squared_change=changes[0],actor1_squared_change=changes[1],actor2_squared_change=changes[2])
        history.append(row);metadata={**meta,**row,'actor_squared_parameter_change':changes}
        torch.save({**metadata,'model':model.state_dict()},out/f'update_{update+1}.pt')
        torch.save({**metadata,'model':model.state_dict()},out/'policy.pt');print(json.dumps(row),flush=True)
        with (out/'training.csv').open('w',newline='') as f:
            writer=csv.DictWriter(f,fieldnames=row,lineterminator='\n');writer.writeheader();writer.writerows(history)
        (out/'aggregation_passes.json').write_text(json.dumps(pass_history,indent=2)+'\n')
    if not all(v>1e-8 for v in changes):raise RuntimeError('An actor did not update')
    (out/'metadata.json').write_text(json.dumps(metadata,indent=2)+'\n')


if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--out',required=True);p.add_argument('--warmstart',required=True)
    p.add_argument('--seed',type=int,default=1701);p.add_argument('--cycles',type=int,default=2)
    p.add_argument('--states',type=int,default=4096);p.add_argument('--epochs',type=int,default=80)
    a=p.parse_args();train(a.out,a.warmstart,a.seed,a.cycles,a.states,a.epochs)
