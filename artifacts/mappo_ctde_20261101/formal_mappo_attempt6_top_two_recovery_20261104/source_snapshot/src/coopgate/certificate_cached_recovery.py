CERTIFICATE_CAPACITY=65536
CERTIFICATE_KEY=types.UniTuple(types.uint64,25)

@njit(cache=True,fastmath=False)
def cached_certificate(state,previous,command,c,radius,certificate_cache,certificate_stats,certificate_capacity):
    x,p,u,q=state.view(np.uint64),previous.view(np.uint64),command.view(np.uint64),c.view(np.uint64)
    key=(x[0,0],x[0,1],x[1,0],x[1,1],x[2,0],x[2,1],p[0],p[1],p[2],u[0],u[1],u[2],
         np.float64(radius).view(np.uint64),q[0],q[1],q[2],q[3],q[4],q[5],q[6],q[7],q[8],q[9],q[10],q[11])
    certificate_stats[0]+=1
    if key in certificate_cache:
        certificate_stats[1]+=1
        return certificate_cache[key]
    certificate_stats[2]+=1
    value=original_certificate(state,previous,command,c,radius)
    if len(certificate_cache)<certificate_capacity:certificate_cache[key]=value
    else:certificate_stats[3]+=1
    return value

@njit(cache=True, fastmath=False)
def project_joint(x, previous, proposed, c, radius, certificate_cache, certificate_stats, certificate_capacity):
    """Nearest proposed/hold/backup joint vertex; no rollout optimizer."""
    commands = np.empty((27, 3))
    scores = np.empty(27)
    for mode in range(27):
        code = mode
        score = 0.0
        for i in range(2, -1, -1):
            option = code % 3
            code //= 3
            backup = max(previous[i] - c[6] * c[1], -c[4])
            v = backup if option == 0 else previous[i] if option == 1 else proposed[i]
            commands[mode, i] = v
            score += (v - proposed[i]) ** 2
        scores[mode] = score
    order = np.argsort(scores, kind='mergesort')
    for m in order:
        if cached_certificate(x, previous, commands[m], c, radius, certificate_cache, certificate_stats, certificate_capacity):
            return (commands[m].copy(), int(m), True)
    return (commands[0].copy(), 0, False)

@njit(cache=True, fastmath=False)
def team_rule_tail(state, previous, step, c, certificate_cache, certificate_stats, certificate_capacity, cutoff=1000000000000.0):
    x = state.copy()
    prev = previous.copy()
    value = 0.0
    transitions = 0
    for k in range(step, round(c[2] / c[1])):
        active = x[:, 0] < c[11]
        if not np.any(active):
            break
        command, _, ok = project_joint(x, prev, constant_proposal(prev, c), c, 0.5, certificate_cache, certificate_stats, certificate_capacity)
        if not ok:
            raise RuntimeError('Rule continuation outside physical contract')
        for i in range(3):
            if active[i]:
                value += (c[1] + 0.05 * abs(command[i] - prev[i])) / 3.0
        if value >= cutoff:
            return (value, transitions)
        if not advance_one(x, command, c):
            raise RuntimeError('Unsafe rule continuation')
        transitions += 1
        prev = command
    return (value, transitions)

@njit(cache=True, fastmath=False)
def deduplicated_joint_rollout(state, previous, step, c, certificate_cache, certificate_stats, certificate_capacity, sweeps=2):
    chosen, _, ok = project_joint(state, previous, constant_proposal(previous, c), c, 0.5, certificate_cache, certificate_stats, certificate_capacity)
    if not ok:
        raise RuntimeError('No certified baseline command')
    best, transitions = team_rule_tail(state, previous, step, c, certificate_cache, certificate_stats, certificate_capacity)
    base_value = best
    if np.all(state[:, 0] >= c[11]):
        return (chosen, best, base_value, transitions)
    seen = np.empty((1 + max(0, sweeps) * 3 * len(LEVELS), 3))
    n_seen = 0
    for _ in range(sweeps):
        improved = False
        for i in (1, 0, 2):
            if state[i, 0] >= c[11]:
                continue
            center = chosen.copy()
            for level in LEVELS:
                if abs(level - previous[i]) > c[6] * c[1] + 1e-08:
                    continue
                proposal = center.copy()
                proposal[i] = level
                for j in range(3):
                    if state[j, 0] >= c[11]:
                        proposal[j] = min(c[5], previous[j] + c[6] * c[1])
                command, _, valid = project_joint(state, previous, proposal, c, 0.5, certificate_cache, certificate_stats, certificate_capacity)
                if not valid:
                    raise RuntimeError('No certificate for candidate')
                if np.array_equal(command, chosen):
                    continue
                duplicate = False
                for k in range(n_seen):
                    if np.array_equal(command, seen[k]):
                        duplicate = True
                        break
                if duplicate:
                    continue
                seen[n_seen] = command
                n_seen += 1
                stage = 0.0
                for j in range(3):
                    if state[j, 0] < c[11]:
                        stage += (c[1] + 0.05 * abs(command[j] - previous[j])) / 3.0
                if stage >= best:
                    continue
                following = state.copy()
                if not advance_one(following, command, c):
                    raise RuntimeError('Unsafe planning transition')
                tail, count = team_rule_tail(following, command, step + 1, c, certificate_cache, certificate_stats, certificate_capacity, best - stage)
                transitions += 1 + count
                if stage + tail < best - 1e-10:
                    chosen = command.copy()
                    best = stage + tail
                    improved = True
        if not improved:
            break
    return (chosen, best, base_value, transitions)

@njit(cache=True, fastmath=False)
def cached_proposal(state, previous, step, packed, cache, stats, capacity, certificate_cache, certificate_stats, certificate_capacity):
    key = proposal_key(state, previous, step, packed)
    stats[0] += 1
    if key in cache:
        saved = cache[key]
        stats[1] += 1
        stats[5] += saved[3]
        return (np.array([saved[0], saved[1], saved[2]]), True, saved[3])
    stats[2] += 1
    try:
        command, _, _, count = deduplicated_joint_rollout(state, previous, step, packed, certificate_cache, certificate_stats, certificate_capacity)
    except Exception:
        stats[4] += 1
        return (np.zeros(3), False, 0)
    stats[3] += 1
    stats[5] += count
    stats[6] += count
    if len(cache) < capacity:
        cache[key] = (command[0], command[1], command[2], count)
    else:
        stats[7] += 1
    return (command, True, count)

@njit(cache=True, fastmath=False)
def recovery_command(state, previous, step, memory_lower, memory_upper, bounds, packed, cache, stats, cache_capacity, certificate_cache, certificate_stats, certificate_capacity):
    """Same command as V34, with explicit failure and recovery indicators."""
    proposal, proposal_available, planning_transitions = cached_proposal(state, previous, step, packed, cache, stats, cache_capacity, certificate_cache, certificate_stats, certificate_capacity)
    certificate_substeps = 0
    if proposal_available:
        result = stopping_certificate(state, previous, proposal, memory_lower, memory_upper, bounds, packed)
        certificate_substeps += result[2]
        if result[0]:
            return (proposal, True, False, False, planning_transitions, certificate_substeps)
    backup = np.maximum(previous - packed[6] * packed[1], -packed[4])
    result = stopping_certificate(state, previous, backup, memory_lower, memory_upper, bounds, packed)
    certificate_substeps += result[2]
    return (backup, bool(result[0]), True, not proposal_available, planning_transitions, certificate_substeps)

@njit(cache=True, fastmath=False)
def pruned_forecast(state, previous, memory, observer_lower, observer_upper, step, tape, gain, drag, retention, bounds, packed, first_command, use_first, cache, stats, cache_capacity, reference_limits, certificate_cache, certificate_stats, certificate_capacity, enable_pruning=True):
    """Original recurrence with a rejection-only check before future planning.

    Error4 denotes a proved baseline-relative rejection, not physical failure.
    First22 return entries preserve the existing forecast interface. Extra
    entries contain bound work and a replayable rejection-prefix proof.
    """
    x, prev, point = (state.copy(), previous.copy(), memory.copy())
    mlo, mhi = (observer_lower.copy(), observer_upper.copy())
    finish, variation, crossing = (np.zeros(3), np.zeros(3), np.zeros(3))
    for i in range(3):
        if x[i, 0] < packed[11]:
            finish[i] = packed[2] - step * packed[1]
            crossing[i] = np.nan
    substeps = round(packed[1] / packed[0])
    states = np.empty((0, 3, 2))
    commands = np.empty((0, 3))
    memories = np.empty((0, substeps, 3))
    errors = np.empty((0, substeps, 3))
    observer_los, observer_his = (np.empty((0, 3)), np.empty((0, 3)))
    recovered = np.zeros(0, np.bool_)
    steps = work = checked_substeps = error = violations = exceeded = bound_calls = bound_work = 0
    planning_work_complete = True
    maximum = 0.0
    lower = np.zeros((3, 2))
    for k in range(step, round(packed[2] / packed[1])):
        active = x[:, 0] < packed[11]
        if not np.any(active):
            break
        if enable_pruning and use_first and (k > step):
            lower, count = optimistic_values(x, prev, point, k, step, tape, gain, retention, packed, finish, variation)
            bound_calls += 1
            bound_work += count
            if np.any(lower > reference_limits + 1e-08):
                error = 4
                break
        if use_first and k == step:
            command = first_command.copy()
        else:
            command, valid, recovery, proposal_failed, count, checks = recovery_command(x, prev, k, mlo, mhi, bounds, packed, cache, stats, cache_capacity, certificate_cache, certificate_stats, certificate_capacity)
            planning_work_complete = planning_work_complete and (not proposal_failed)
            work += count
            checked_substeps += checks
            if not valid:
                error = 2
                break
        check = stopping_certificate(x, prev, command, mlo, mhi, bounds, packed)
        checked_substeps += check[2]
        if not check[0]:
            error = 3
            break
        for i in range(3):
            if active[i]:
                variation[i] += abs(command[i] - prev[i])
        for sub in range(substeps):
            before = x[:, 0].copy()
            mlo, mhi = memory_step(mlo, mhi, command, bounds)
            current_error = 0.0
            for i in range(3):
                point[i] = retention[i] * point[i] + (1.0 - retention[i]) * command[i]
                applied = gain[i] * point[i] - drag[i] * x[i, 1] ** 2 + tape[k * substeps + sub, i]
                current_error = max(current_error, abs(applied - command[i]))
                x[i, 1] = min(packed[3], max(0.0, x[i, 1] + packed[0] * applied))
                x[i, 0] += packed[0] * x[i, 1]
                if np.isnan(crossing[i]):
                    crossing[i] = crossing_time(before[i], x[i, 0], packed[11], (k - step) * packed[1] + sub * packed[0], packed[0])
            maximum = max(maximum, current_error)
            exceeded += int(current_error > 0.5 + 1e-09)
            violations += int(not transition_values(before[0], before[1], before[2], x[0, 0], x[1, 0], x[2, 0], packed))
        for i in range(3):
            if active[i] and x[i, 0] >= packed[11]:
                finish[i] = (k - step + 1) * packed[1]
        prev = command.copy()
        steps += 1
    values = np.zeros((3, 2))
    for i in range(3):
        values[i, 0], values[i, 1] = (finish[i] + 0.05 * variation[i], finish[i])
    complete = bool(np.all(x[:, 0] >= packed[11]) and error == 0 and (violations == 0))
    return (values, crossing, complete, error, steps, work, checked_substeps, maximum, exceeded, x, point, mlo, mhi, violations, states, commands, memories, errors, observer_los, observer_his, recovered, planning_work_complete, bound_calls, bound_work, lower, prev, finish, variation)


class CertificateCachedRecoveryGate(AdmissibleRecoveryGate):
    def predict(self,state,previous,mlo,mhi,command,path):
        if getattr(self,'_cache_step',None)!=self.step:
            self._plan_cache,self._cache_stats=make_cache();self._cache_step=self.step
        limits=self._reference_limits.get(path)
        result=pruned_forecast(state,previous,self.memory,mlo,mhi,self.step,self.tapes[path],
            self.gain,self.drag,self.retention,self.bounds,self.packed,
            np.zeros(3) if command is None else command,command is not None,
            self._plan_cache,self._cache_stats,CAPACITY,np.zeros((3,2)) if limits is None else limits,
            self._certificate_cache,self._certificate_stats,CERTIFICATE_CAPACITY,
            command is not None and limits is not None)
        if command is None and result[2]:self._reference_limits[path]=result[0].copy()
        self._bound_calls+=int(result[22]);self._bound_work+=int(result[23])
        if result[3]==4:
            self._rejections.append(dict(path=path,forecast_prefix_steps=int(result[4]),
                lower_values=result[24].tolist(),reference_limits=limits.tolist(),
                prefix_state=result[9].tolist(),prefix_memory=result[10].tolist(),
                prefix_previous=result[25].tolist(),prefix_finish=result[26].tolist(),
                prefix_variation=result[27].tolist(),root_step=self.step))
        return result[:22]

    def select(self,state,previous,unused=None):
        started=time.perf_counter()
        self._certificate_cache=Dict.empty(key_type=CERTIFICATE_KEY,value_type=types.boolean)
        self._certificate_stats=np.zeros(4,dtype=np.int64)
        command,info=super().select(state,previous,unused)
        values=self._certificate_stats.tolist()
        if values[0]!=values[1]+values[2]:raise RuntimeError('Certificate cache accounting mismatch')
        info.update(nominal_certificate_cache=dict(zip(('requests','hits','misses','capacity_skips'),values)),
            nominal_certificate_cache_entries=len(self._certificate_cache),
            nominal_certificate_cache_capacity=CERTIFICATE_CAPACITY,
            gate_ms=1000*(time.perf_counter()-started))
        return command,info
