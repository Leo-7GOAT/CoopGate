ROOT=Path(__file__).resolve().parents[1]
EXTRA=['certificate_cache','certificate_stats','certificate_capacity']


def clone(function,insertion=None):
    tree=ast.parse(inspect.getsource(function.py_func));fn=tree.body[0]
    args=[ast.arg(arg=n) for n in EXTRA]
    if insertion is None:fn.args.args.extend(args)
    else:fn.args.args[insertion:insertion]=args
    for node in ast.walk(fn):
        if not isinstance(node,ast.Call) or not isinstance(node.func,ast.Name):continue
        name=node.func.id
        if name=='robust_certificate':
            node.func.id='cached_certificate';node.args.extend(ast.Name(id=n,ctx=ast.Load()) for n in EXTRA)
        elif name in ('project_joint','deduplicated_joint_rollout','team_rule_tail'):
            index=5 if name=='project_joint' else 4
            node.args[index:index]=[ast.Name(id=n,ctx=ast.Load()) for n in EXTRA]
        elif name in ('cached_proposal','recovery_command'):
            node.args.extend(ast.Name(id=n,ctx=ast.Load()) for n in EXTRA)
    return ast.unparse(ast.fix_missing_locations(tree))+'\n\n'


